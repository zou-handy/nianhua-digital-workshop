function buildNianhuaImagePrompt(subject) {
  const safeSubject = String(subject || '').trim();
  const prompt = [
    '创作一幅全彩佛山木版年画。',
    '主题：' + safeSubject + '。',
    '画面必须明显使用朱砂红、明黄、青绿色和黑色四种纯色，并保留宣纸白背景。',
    '朱砂红约占主体色块的35%，明黄约占25%，青绿色约占25%；黑色不超过15%，只能用于粗犷轮廓、眉眼和少量细节，严禁用黑色填满人物、服饰或背景。',
    '人物或主体完整居中，构图饱满对称，具有佛山门神年画的喜庆、强烈、装饰性。',
    '严格只使用朱砂红、明黄、青绿色、墨黑和宣纸白，不得产生第五种颜色。',
    '每个封闭区域只能使用一种完全均匀的纯色色块，颜色边界硬朗清晰，适合直接拆成红、黄、绿、黑四块套印木版。',
    '采用传统木刻粗线条和平涂套色效果。禁止任何形式的渐变、综合色、半透明叠色、柔光、阴影、高光、腮红、景深、材质反光、写实光影、立体渲染和灰色过渡。',
    '相同颜色区域必须保持完全一致的色值，不得用深红与浅红、深绿与浅绿表现明暗。',
    '最终结果必须是高饱和度全彩年画，不能是黑白木刻、单色版画、水墨画或素描。'
  ].join('');

  const negativePrompt = [
    '黑白画',
    '单色画',
    '黑色占满画面',
    '黑色大面积填充',
    '灰度图',
    '低饱和度',
    '水墨画',
    '素描',
    '黑白木刻',
    '暗色背景',
    '写实摄影',
    '3D渲染',
    '渐变',
    '多色渐变',
    '明暗渐变',
    '综合色',
    '半透明叠色',
    '阴影',
    '投影',
    '高光',
    '腮红',
    '柔光',
    '材质反光',
    '深浅色阶',
    '模糊边缘',
    '文字',
    '水印'
  ].join(', ');

  return { prompt, negativePrompt };
}

/**
 * 构造「自拍/实拍图 -> 国潮二次元平涂木版年画」专属提示词
 * 将多模态视觉模型识别出的人物发型、配饰、神态、服装色系融合进二次元赛璐璐+佛山木版年画平涂风格
 */
function buildAnimeNianhuaPrompt(visionTraits, userHint) {
  const cleanTraits = String(visionTraits || '').trim() || '青年人物半身像，面带微笑，神态喜庆精神';
  const extraHint = String(userHint || '').trim();
  const prompt = [
    '创作一幅国潮二次元动漫插画风格的佛山木版年画人物半身像。',
    '画中主角外貌与动作严格还原以下特征：' + cleanTraits + (extraHint ? ('，主题氛围：' + extraHint) : '') + '。',
    '采用精致灵动的二次元动漫五官开相与日式赛璐璐（Cel-shading）硬边平涂上色，融合佛山非遗木版年画的粗犷刀刻松烟墨黑勾线、金鳞祥云与岭南喜庆装饰。',
    '画面必须使用高饱和纯色色块平涂：万年红（朱砂红）、石黄（明黄）、石绿（翠青）、靛青蓝、松烟墨黑，并保留干净的宣纸米白背景。',
    '每个封闭区域只能填充完全均匀的单一纯色，颜色交界硬朗分明，严禁出现写实摄影渐变、柔和阴影、3D模糊过渡或杂乱噪点，确保完美适合直接拆分为多块套印木版。'
  ].join('');

  const negativePrompt = [
    '真人写实摄影',
    '照片感',
    '黑白画',
    '灰度图',
    '3D写实渲染',
    '柔和渐变',
    '复杂阴影过渡',
    '模糊边缘',
    '恐怖畸形五官',
    '多余手指',
    '文字水印',
    '暗沉脏色背景'
  ].join(', ');

  return { prompt, negativePrompt };
}

module.exports = {
  buildNianhuaImagePrompt,
  buildAnimeNianhuaPrompt
};
